def extract_room_number(office_number):
    """Extract room numbers from office number field"""
    if pd.isna(office_number) or not office_number:
        return None
    
    office_str = str(office_number).strip()
    room_numbers = []
    
    # Check for ground floor rooms (जी- pattern)
    if "जी" in office_str:
        # Handle specific patterns first
        if '-' in office_str and not ('/' in office_str or ',' in office_str):
            # Handle patterns like जी-14-15 (range) - with or without spaces
            range_match = re.search(r'जी\s*[-]?\s*(\d+)\s*[-]\s*(\d+)', office_str)
            if range_match:
                start_num = int(range_match.group(1))
                end_num = int(range_match.group(2))
                for num in range(start_num, end_num + 1):
                    room_numbers.append(f"जी-{num}")
            else:
                # Extract individual numbers
                number_pattern = re.findall(r'(\d+[A-Z]?)', office_str)
                for num in number_pattern:
                    room_numbers.append(f"जी-{num}")
        else:
            # Handle patterns like जी-09/10, जी-1,2,3 etc.
            if '/' in office_str or ',' in office_str or 'ते' in office_str:
                number_pattern = re.findall(r'(\d+[A-Z]?)', office_str)
                for num in number_pattern:
                    room_numbers.append(f"जी-{num}")
            else:
                # Extract single number
                match = re.search(r'जी\s*[-]?\s*(\d+[A-Z]?)', office_str)
                if match:
                    room_numbers.append(f"जी-{match.group(1)}")
    
    # Check for room numbers (रूम नं. pattern) - handles all floors
    if "रूम नं" in office_str:
        # Handle specific patterns first
        if '-' in office_str and not ('/' in office_str or ',' in office_str):
            # Handle patterns like रूम नं.-401 ते 406 (range)
            range_match = re.search(r'(\d+)\s*ते\s*(\d+)', office_str)
            if range_match:
                start_num = int(range_match.group(1))
                end_num = int(range_match.group(2))
                for num in range(start_num, end_num + 1):
                    room_numbers.append(str(num))
            else:
                # Extract individual numbers
                number_pattern = re.findall(r'(\d+[A-Z]?)', office_str)
                for num in number_pattern:
                    room_numbers.append(num)
        else:
            # Handle patterns like रूम नं.-101/102, रूम नं. 101,102 etc.
            if '/' in office_str or ',' in office_str:
                number_pattern = re.findall(r'(\d+[A-Z]?)', office_str)
                for num in number_pattern:
                    room_numbers.append(num)
            else:
                # Extract single number - improved regex to handle extra spaces
                match = re.search(r'रूम\s*नं\.?\s*[-]?\s*(\d+[A-Z]?)', office_str)
                if match:
                    room_numbers.append(match.group(1))
                else:
                    # Fallback: try to extract any number after "रूम नं"
                    fallback_match = re.search(r'रूम\s*नं[^0-9]*(\d+[A-Z]?)', office_str)
                    if fallback_match:
                        room_numbers.append(fallback_match.group(1))
    
    # Check for direct room number patterns (without "रूम नं" prefix)
    # This handles cases like "201", "301", "401" etc.
    if not room_numbers and re.search(r'^\d+[A-Z]?$', office_str.strip()):
        room_numbers.append(office_str.strip())
    
    # Check for room number patterns with spaces or other separators
    if not room_numbers:
        # Look for patterns like "201, 202" or "301-305" etc.
        number_pattern = re.findall(r'(\d+[A-Z]?)', office_str)
        if number_pattern:
            # Filter out very small numbers that might be part of other text
            for num in number_pattern:
                if len(num) >= 2:  # Room numbers are typically 2+ digits
                    room_numbers.append(num)
    
    # Remove duplicates and return list
    if room_numbers:
        return list(set(room_numbers))
    
    return None

def infer_floor_from_room(room_number: str):
    """Infer floor in Marathi from a room number when floor is missing.
    Returns one of: 'पहिला मजला', 'दुसरा मजला', 'तिसरा मजला', 'चौथा मजला', 'तळ मजला' or None.
    """
    if not room_number:
        return None
    rn = str(room_number).strip()
    # Ground floor formats handled elsewhere (e.g., 'जी-19', 'G-19')
    if rn.lower().startswith('g') or rn.startswith('जी'):
        return 'तळ मजला'
    if not rn[0].isdigit():
        return None
    first_digit = rn[0]
    if first_digit == '1':
        return 'पहिला मजला'
    if first_digit == '2':
        return 'दुसरा मजला'
    if first_digit == '3':
        return 'तिसरा मजला'
    if first_digit == '4':
        return 'चौथा मजला'
    return None

